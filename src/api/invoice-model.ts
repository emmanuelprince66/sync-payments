/**
 * The app's invoice model, shared by the live service (`./invoices`) and the mock
 * store (`./sample/invoices`). Backend payloads are mapped into these shapes, so
 * screens never see wire field names.
 */

/** Workflow status as saved. Viewed is a Sent invoice the customer has opened. */
export type InvoiceStatus = 'Draft' | 'Approved' | 'Sent' | 'Viewed' | 'Paid' | 'Overdue' | 'Void'

/** The three printable invoice designs. */
export const INVOICE_DESIGNS = ['Classic', 'Ledger', 'Studio'] as const
export type InvoiceDesign = (typeof INVOICE_DESIGNS)[number]

export const INVOICE_PAYMENT_METHODS = ['Bank transfer', 'Cash', 'Card', 'POS', 'Other'] as const
export type InvoicePaymentMethod = (typeof INVOICE_PAYMENT_METHODS)[number]

export type InvoiceTaxMode = 'exclusive' | 'inclusive' | 'none'

/** A saved product or service, reusable across invoice lines. The description is its name. */
export type InvoiceItem = { id: string; description: string; price: number; taxRate: number; account: string; createdAt: string }

/** Fields a saved item is created with (`description` required). */
export type InvoiceItemInput = Omit<InvoiceItem, 'id' | 'createdAt'>

/** One line as saved: `amount` is qty × price less discount, `tax` the tax on it. */
export type InvoiceLineRecord = {
  description: string
  qty: number
  price: number
  discount: number
  taxRate: number
  account: string
  itemId: string
  amount: number
  tax: number
}

export type InvoicePayment = {
  id: string
  amount: number
  /** ISO day the customer paid. */
  date: string
  method: InvoicePaymentMethod
  note: string
  recordedBy: string
  /** ISO timestamp. */
  recordedAt: string
  /** Reversed payments stay in the history but no longer count toward the amount paid. */
  reversed: boolean
  reversedAt: string
  reversedBy: string
}

export type InvoiceActivityType = 'created' | 'updated' | 'approved' | 'sent' | 'viewed' | 'reminder' | 'payment' | 'payment_reversed' | 'paid' | 'voided'
export type InvoiceActivity = { id: string; type: InvoiceActivityType; message: string; by: string; at: string }

/** Branding the printable document is drawn with. */
export type InvoiceBranding = { accent: string; legalName: string; address: string; logoUrl: string }

export type Invoice = {
  /** Backend id, used in URLs and API paths. */
  id: string
  /** The invoice number shown to people, e.g. INV-1052. */
  number: string
  /** Auto-generated by the backend; never sent by us. */
  reference: string
  client: string
  clientId: string
  clientEmail: string
  clientPhone: string
  /** Total, tax included. */
  amount: number
  subtotal: number
  tax: number
  /** Sum of payments that are not reversed. */
  amountPaid: number
  balance: number
  /** ISO dates. */
  issued: string
  due: string
  status: InvoiceStatus
  /** The customer opened the public link (`viewed_at` set, or status VIEWED on list rows). */
  viewed: boolean
  /** ISO timestamp of the first view; empty when not viewed or on list rows. */
  viewedAt: string
  taxMode: InvoiceTaxMode
  design: InvoiceDesign
  branding: InvoiceBranding
  note: string
  lines: InvoiceLineRecord[]
  payments: InvoicePayment[]
  activity: InvoiceActivity[]
  /** The customer-facing link, on Sent and later invoices. */
  publicUrl: string
  createdBy: string
  /** ISO timestamp. */
  createdAt: string
}

export type InvoiceAnalyticsMonth = { month: string; sent: number; paid: number }
export type DocumentFlowItem = { label: string; count: number; amount: number | null; color: string }

/** From GET …/analytics/. Text figures read "—" when the server sends null. */
export type InvoiceSummary = {
  /** Invoices not yet paid, by count (APPROVED + SENT + VIEWED + OVERDUE). */
  outstandingCount: number
  overdueCount: number
  paidThisMonth: number
  /** "+16% from last month", or "—" when there is nothing to compare with. */
  paidChange: string
  averagePaidDays: string
  collectionRate: string
  /** Balance still expected on open invoices. */
  expectedCash: number
  /** Last six months, sent vs paid amounts. */
  months: InvoiceAnalyticsMonth[]
  flow: DocumentFlowItem[]
}

/** What a customer has paid and still owes across their invoices. */
export type CustomerInvoiceSummary = { totalPaid: number; totalUnpaid: number; overdue: number; invoiceCount: number }
/** Bulk summaries keyed by customer id. */
export type CustomerInvoiceSummaries = Record<string, CustomerInvoiceSummary>

/** Fields a draft is created or edited with. Totals are worked out by the server. */
export type InvoiceInput = {
  customerId: string
  issueDate: string
  dueDate: string
  taxMode: InvoiceTaxMode
  design: InvoiceDesign
  accent: string
  legalName: string
  address: string
  note: string
  lines: Omit<InvoiceLineRecord, 'amount' | 'tax'>[]
}

/** The client as picked on the form; the mock store snapshots it (the server does its own). */
export type InvoiceClientSnapshot = { name: string; email: string; phone: string }

export type InvoiceReminderChannel = 'email' | 'whatsapp' | 'share'
/** `sendSucceeded` is null for share (nothing is sent by the server); `message` explains a failure. */
export type InvoiceReminderResult = { channel: InvoiceReminderChannel; publicUrl: string; sendAttempted: boolean; sendSucceeded: boolean | null; message: string }

export type InvoiceListParams = { page: number; limit: number; search: string; status: string; customer: string; startDate: string; endDate: string }
export type InvoiceListResult = { invoices: Invoice[]; total: number; pages: number }

/** What the customer still owes and where the invoice stands, worked out from payments and the due date. */
export type InvoicePaymentState = 'Draft' | 'Approved' | 'Pending' | 'Part paid' | 'Overdue' | 'Paid' | 'Void'

export const roundMoney = (value: number) => Math.round(value * 100) / 100

export const todayIso = () => {
  const date = new Date()
  return `${date.getFullYear()}-${String(date.getMonth() + 1).padStart(2, '0')}-${String(date.getDate()).padStart(2, '0')}`
}

export const invoiceBalance = (invoice: Pick<Invoice, 'balance'>) => Math.max(roundMoney(invoice.balance), 0)

export const invoicePaymentState = (invoice: Pick<Invoice, 'status' | 'balance' | 'amountPaid' | 'due'>, today = todayIso()): InvoicePaymentState => {
  if (invoice.status === 'Void') return 'Void'
  if (invoice.status === 'Draft') return 'Draft'
  if (invoice.status === 'Paid' || invoiceBalance(invoice) <= 0) return 'Paid'
  if (invoice.status === 'Overdue' || (invoice.due && invoice.due < today)) return 'Overdue'
  if ((invoice.amountPaid ?? 0) > 0) return 'Part paid'
  return invoice.status === 'Approved' ? 'Approved' : 'Pending'
}

/** States where the customer still owes money. */
export const OPEN_PAYMENT_STATES: InvoicePaymentState[] = ['Approved', 'Pending', 'Part paid', 'Overdue']

/** Field edits are only accepted while a draft; after that only the status moves. */
export const isEditable = (invoice: Pick<Invoice, 'status'>) => invoice.status === 'Draft'

/** Sent or later: the invoice has a public link and can be chased. */
export const isOut = (invoice: Pick<Invoice, 'status'>) => ['Sent', 'Viewed', 'Paid', 'Overdue'].includes(invoice.status)
